-- ========================================================================================
-- Seeds the shared exercise_library with ~647 named exercises across
-- 20 categories, organized by muscle group / training type per the
-- user-provided list. Idempotent — an `on conflict` guard keyed on (name, category)
-- means re-running this is safe and won't create duplicate rows; it DOES require
-- a unique index on (name, category) to work, added below if not already present.
--
-- `default_sets`/`default_reps`/`default_time` are starting suggestions only (same
-- role as the library's existing seeded exercises) — a reasonable per-category
-- default, not a per-exercise prescription; a coach edits these per trainee/program
-- when actually assigning. `default_weight` is left null throughout (coach fills
-- in real load; several categories — bodyweight, cardio, stretching — have no
-- weight at all). `created_by` is left null — these are shared/system-seeded, not
-- owned by any one coach (the library is already "any coach can edit/delete",
-- not scoped to a creator).
--
-- The SAME exercise name intentionally appears under more than one category where
-- it genuinely belongs to more than one (e.g. "Pull-up" under Back, Biceps, AND
-- Bodyweight and Calisthenics; "Romanian deadlift" under both Hamstrings and
-- Glutes) — each is its own row, since category is single-valued per row and a
-- coach browsing by category should find it there. Exact repeats WITHIN the same
-- category (a few existed in the source list) were de-duplicated before generating
-- this file, not inserted twice.
-- ========================================================================================

